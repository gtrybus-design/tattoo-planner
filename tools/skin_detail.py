"""Fine skin detail as a small tile that repeats over the body at real size: the surface texture of skin (a normal
map) and how glossy it is from place to place (a roughness map). Generated here, so it is ours (no licence).

usage: .venv/bin/python tools/skin_detail.py [project dir]      (needs numpy + pillow; writes skin-detail.js)

Real skin's surface (skin microrelief) is a network of shallow furrows: primary lines that cut it into polygons
1-3 mm across, finer secondary lines dividing those into cells a few tenths of a millimetre across, and pores
(hair follicles and sweat ducts) as small pits, mostly where furrows cross. Each network here is the edge set of
a periodic jittered cell pattern (Worley: where the nearest and second-nearest cell centres are about equally
far, a furrow), so the tile wraps seamlessly. Depths are in millimetres; the page scales the effect.

The tile is TILE_MM across. The page repeats it over the skin map, whose UVs are true scale (uv_atlas.py: 1 UV
unit = sheet size), so each pore and furrow keeps its real size wherever it is on the body.
"""
import base64, io, os, sys
import numpy as np
from PIL import Image

out = sys.argv[1] if len(sys.argv) > 1 else '.'
TILE_MM = 25.0          # tile size (mm)
PX = 1024               # tile resolution (~0.024 mm per pixel)
rng = np.random.default_rng(7)
mm = TILE_MM / PX
yy, xx = np.mgrid[0:PX, 0:PX].astype(np.float32) * mm         # pixel positions (mm)


def worley(cells):
    """Distance to the nearest and second-nearest jittered cell centre (periodic), and the nearest one's index."""
    pts = (np.stack(np.mgrid[0:cells, 0:cells], -1) + rng.uniform(0.15, 0.85, (cells, cells, 2))) * (TILE_MM / cells)
    c = TILE_MM / cells
    ci, cj = (yy / c).astype(int) % cells, (xx / c).astype(int) % cells
    f1 = np.full(xx.shape, 1e9, np.float32); f2 = f1.copy(); idx = np.zeros(xx.shape, np.int32)
    for di in (-1, 0, 1):
        for dj in (-1, 0, 1):
            ni, nj = (ci + di) % cells, (cj + dj) % cells
            p = pts[ni, nj]
            # the neighbour's centre, moved by a whole tile where the neighbour wrapped around
            py = p[..., 0] + np.where(ci + di < 0, -TILE_MM, np.where(ci + di >= cells, TILE_MM, 0))
            px = p[..., 1] + np.where(cj + dj < 0, -TILE_MM, np.where(cj + dj >= cells, TILE_MM, 0))
            d = np.hypot(yy - py, xx - px)
            closer = d < f1
            f2 = np.where(closer, f1, np.minimum(f2, d)); idx = np.where(closer, ni * cells + nj, idx); f1 = np.where(closer, d, f1)
    return f1, f2, idx


def periodic_noise(scale_mm):
    """Smooth random undulation that wraps (white noise, low-passed in the frequency domain), unit variance."""
    k = np.fft.fftfreq(PX, d=mm)
    kk = np.hypot(*np.meshgrid(k, k))
    n = np.fft.ifft2(np.fft.fft2(rng.standard_normal((PX, PX))) * np.exp(-(kk * scale_mm) ** 2)).real
    return (n / n.std()).astype(np.float32)


# primary lines: cells ~2.5 mm, furrows ~60 um deep and ~0.12 mm wide; secondary: cells ~0.6 mm, ~20 um deep
f1, f2, _ = worley(int(TILE_MM / 2.5))
primary = np.exp(-((f2 - f1) / 0.12) ** 2)
g1, g2, gi = worley(int(TILE_MM / 0.6))
secondary = np.exp(-((g2 - g1) / 0.05) ** 2)
# pores: about one in four fine-cell corners, where the fine furrows meet (all three distances alike), ~25 um deep
corner = np.exp(-((g2 - g1) / 0.06) ** 2) * np.exp(-(g1 / 0.25 - 1) ** 2 * 6)
keep = rng.random(int(TILE_MM / 0.6) ** 2) < 0.25
pores = corner * keep[gi]
depth = rng.uniform(0.35, 1.0, int(TILE_MM / 0.6) ** 2)[gi]        # (furrows vary: some cells are barely marked)
dome = -(np.clip(g1 / 0.35, 0, 1) ** 2)                             # (each fine cell a little domed, not flat)
height = -0.055 * primary - 0.020 * secondary * depth - 0.025 * pores + 0.006 * dome + 0.010 * periodic_noise(1.5)   # (mm)

# normal map (tangent space, +y up as three.js expects): slopes by central differences, wrapping
dx = (np.roll(height, -1, 1) - np.roll(height, 1, 1)) / (2 * mm)
dy = (np.roll(height, -1, 0) - np.roll(height, 1, 0)) / (2 * mm)
N = np.stack([-dx, dy, np.ones_like(dx)], -1); N /= np.linalg.norm(N, axis=-1, keepdims=True)
normal_img = Image.fromarray(np.round((N * 0.5 + 0.5) * 255).astype(np.uint8), 'RGB')
# roughness (green channel, multiplies the material's): the furrows and pores are a little rougher than the plateaus
rough = 0.82 + 0.18 * np.clip(primary + 0.7 * secondary + pores, 0, 1)
rough_img = Image.fromarray(np.round(np.stack([rough] * 3, -1) * 255).astype(np.uint8), 'RGB').resize((PX // 2, PX // 2), Image.LANCZOS)


def data_url(img, fmt, **kw):
    b = io.BytesIO(); img.save(b, fmt, **kw)
    return f'data:image/{fmt.lower()};base64,' + base64.b64encode(b.getvalue()).decode()


with open(f'{out}/skin-detail.js.tmp', 'w') as fh:
    fh.write('// Generated by tools/skin_detail.py: a repeating tile of skin surface detail (furrows and pores), at real size.\n')
    fh.write('window.SKIN_DETAIL = ' + str({'tileMm': TILE_MM, 'normal': data_url(normal_img, 'PNG', optimize=True),
                                               'rough': data_url(rough_img, 'JPEG', quality=90)}).replace("'", '"') + ';\n')
os.replace(f'{out}/skin-detail.js.tmp', f'{out}/skin-detail.js')
print(f'wrote {out}/skin-detail.js ({os.path.getsize(f"{out}/skin-detail.js") / 1e6:.1f} MB): {TILE_MM:g} mm tile, '
      f'{mm * 1000:.0f} um per pixel, height range {height.min() * 1000:.0f}..{height.max() * 1000:.0f} um', file=sys.stderr)
